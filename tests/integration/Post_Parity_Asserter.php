<?php
/**
 * Source/destination post parity asserter for integration tests.
 *
 * @package Safe_Publish
 */

declare(strict_types=1);

namespace Safe_Publish\Tests\Integration;

use PHPUnit\Framework\TestCase;
use Safe_Publish\Utils\Options;
use WP_Error;
use WP_Post;

/**
 * Schema-driven asserter for source-to-destination post parity.
 *
 * Models every wp_posts column, every dest meta key, and every term
 * assignment explicitly: each is either checked for parity, listed in a
 * divergence / plugin-added registry with the documented reason, or listed as
 * deferred (covered in a later test phase). The assert_no_unmodeled_*
 * checks fail loudly if a column, meta key, or term assignment ever appears
 * outside these categories — so a future schema change or import-pipeline
 * tweak surfaces as a test failure rather than silent skipping.
 */
final class Post_Parity_Asserter {

	/**
	 * Canonical list of wp_posts columns the asserter classifies.
	 *
	 * Updated when WordPress changes the schema. Each column must appear in
	 * exactly one of: identity / content / status / timing / misc rules, the
	 * divergence registry, or the deferred registry.
	 *
	 * @var list<string>
	 */
	private const WP_POSTS_COLUMNS = array(
		'ID',
		'post_author',
		'post_date',
		'post_date_gmt',
		'post_content',
		'post_title',
		'post_excerpt',
		'post_status',
		'comment_status',
		'ping_status',
		'post_password',
		'post_name',
		'to_ping',
		'pinged',
		'post_modified',
		'post_modified_gmt',
		'post_content_filtered',
		'post_parent',
		'guid',
		'menu_order',
		'post_type',
		'post_mime_type',
		'comment_count',
	);

	/**
	 * Identity-style columns: post_type, slug.
	 *
	 * Source REST field => wp_posts column.
	 *
	 * @var array<string, string>
	 */
	private const IDENTITY_COLUMNS = array(
		'type' => 'post_type',
		'slug' => 'post_name',
	);

	/**
	 * Content-style columns checked for parity. post_content is deferred —
	 * see DEFERRED_REGISTRY.
	 *
	 * Source REST field => wp_posts column. Title/excerpt come as
	 * `[ 'raw' => string ]` and need .raw unwrapping (see lookup helper).
	 *
	 * @var array<string, string>
	 */
	private const CONTENT_COLUMNS = array(
		'title'   => 'post_title',
		'excerpt' => 'post_excerpt',
	);

	/**
	 * Status-style columns checked for parity.
	 *
	 * Source REST field => wp_posts column. post_status diverges by design
	 * (see DIVERGENCE_REGISTRY) so it's not in this mapping.
	 *
	 * @var array<string, string>
	 */
	private const STATUS_COLUMNS = array(
		'comment_status' => 'comment_status',
		'ping_status'    => 'ping_status',
		'password'       => 'post_password',
	);

	/**
	 * Misc columns checked for parity.
	 *
	 * Source REST field => wp_posts column. Columns whose source value is
	 * always the WP default (to_ping, pinged, post_content_filtered) are
	 * checked against the empty default; comment_count is always 0 because
	 * comments aren't migrated.
	 *
	 * @var array<string, string>
	 */
	private const MISC_COLUMNS = array(
		'menu_order' => 'menu_order',
	);

	/**
	 * Columns whose source value isn't part of the REST body but whose dest
	 * value is expected to be the WordPress default. Checked against the
	 * provided default string.
	 *
	 * @var array<string, string>
	 */
	private const DEFAULT_VALUE_COLUMNS = array(
		'to_ping'               => '',
		'pinged'                => '',
		'post_content_filtered' => '',
		'post_mime_type'        => '',
		'comment_count'         => '0',
	);

	/**
	 * Columns expected to differ between source and dest. Skipped during
	 * parity checks; the reason is documented for reviewers.
	 *
	 * @var array<string, string>
	 */
	private const DIVERGENCE_REGISTRY = array(
		'ID'                => 'namespace difference (source vs dest WordPress)',
		'post_status'       => 'imported as draft regardless of source status',
		'post_date'         => 'set to import time, source publish date not propagated',
		'post_date_gmt'     => 'WordPress stores 0000-00-00 00:00:00 for drafts',
		'post_modified'     => 'set to import time, not source modified time',
		'post_modified_gmt' => 'set to import time, not source modified time',
		'guid'              => 'regenerated by dest WordPress, source GUID not propagated',
	);

	/**
	 * Columns whose parity check is deferred to a later test phase. Each
	 * entry names the phase that will cover it.
	 *
	 * @var array<string, string>
	 */
	private const DEFERRED_REGISTRY = array(
		'post_content' => 'deferred: URL/ID rewriting parity (later phase)',
		'post_author'  => 'deferred: author resolution semantics (later phase)',
		'post_parent'  => 'deferred: hierarchical post support not in seeder yet',
	);

	/**
	 * Plugin-added meta keys the importer writes on every imported post. The
	 * expected value per post is computed in assert_plugin_added_meta() — this
	 * map only documents what each key means so reviewers can audit the set.
	 *
	 * META_IMPORT_DATE_GMT's value is a wall-clock timestamp computed at
	 * import time, so it gets a format check rather than a value-equality
	 * check.
	 *
	 * @var array<string, string>
	 */
	private const PLUGIN_ADDED_META = array(
		Options::META_SOURCE_POST_ID      => 'source post ID',
		Options::META_SOURCE_LINK         => 'source post URL',
		Options::META_IMPORTED_FROM       => 'plugin marker',
		Options::META_IMPORT_DATE_GMT     => 'GMT timestamp (format-checked)',
		Options::META_SOURCE_AUTHOR_EMAIL => 'source author email',
		Options::META_SOURCE_AUTHOR_LOGIN => 'source author login',
	);

	/**
	 * Meta keys WordPress core may attach automatically to imported posts.
	 * Allowed when present, absence is fine. Empty for now; populate when
	 * runs reveal core defaults that need an allowlist entry (e.g. _edit_lock,
	 * _edit_last when posts are opened in the editor).
	 *
	 * @var array<string, string>
	 */
	private const WP_DEFAULT_META = array();

	/**
	 * Meta keys whose parity check is deferred to a later test phase. Allowed
	 * but not asserted; entries move into PLUGIN_ADDED_META when the matching
	 * phase ships and starts emitting them.
	 *
	 * @var array<string, string>
	 */
	private const DEFERRED_META = array(
		'_thumbnail_id'                     => 'featured-image parity (PR 2c)',
		Options::META_SOURCE_POST_PARENT_ID => 'hierarchical post support',
	);

	/**
	 * Taxonomies whose term assignments are verified for parity. Aligned with
	 * the seeder's term_config(); extend alongside it when new taxonomies are
	 * added.
	 *
	 * @var list<string>
	 */
	private const TERM_TAXONOMIES_CHECKED = array( 'category', 'post_tag' );

	/**
	 * Asserts parity for identity-style columns (type, slug).
	 *
	 * @param array<string, mixed> $source_body Source REST response body.
	 * @param WP_Post              $dest_post   Imported destination post.
	 * @param TestCase             $test        Active test case.
	 */
	public static function assert_identity_columns(
		array $source_body,
		WP_Post $dest_post,
		TestCase $test
	): void {
		self::assert_mapped_columns(
			self::IDENTITY_COLUMNS,
			$source_body,
			$dest_post,
			$test
		);
	}

	/**
	 * Asserts parity for content-style columns (title, excerpt).
	 *
	 * Note: post_content is intentionally NOT checked here — see
	 * DEFERRED_REGISTRY.
	 *
	 * @param array<string, mixed> $source_body Source REST response body.
	 * @param WP_Post              $dest_post   Imported destination post.
	 * @param TestCase             $test        Active test case.
	 */
	public static function assert_content_columns(
		array $source_body,
		WP_Post $dest_post,
		TestCase $test
	): void {
		self::assert_mapped_columns(
			self::CONTENT_COLUMNS,
			$source_body,
			$dest_post,
			$test
		);
	}

	/**
	 * Asserts parity for status-style columns.
	 *
	 * @param array<string, mixed> $source_body Source REST response body.
	 * @param WP_Post              $dest_post   Imported destination post.
	 * @param TestCase             $test        Active test case.
	 */
	public static function assert_status_columns(
		array $source_body,
		WP_Post $dest_post,
		TestCase $test
	): void {
		self::assert_mapped_columns(
			self::STATUS_COLUMNS,
			$source_body,
			$dest_post,
			$test
		);
	}

	/**
	 * Asserts miscellaneous column parity (menu_order) and that columns with
	 * no REST-side value land on the WordPress default on the dest.
	 *
	 * @param array<string, mixed> $source_body Source REST response body.
	 * @param WP_Post              $dest_post   Imported destination post.
	 * @param TestCase             $test        Active test case.
	 */
	public static function assert_misc_columns(
		array $source_body,
		WP_Post $dest_post,
		TestCase $test
	): void {
		self::assert_mapped_columns(
			self::MISC_COLUMNS,
			$source_body,
			$dest_post,
			$test
		);

		$dest_array = $dest_post->to_array();

		foreach ( self::DEFAULT_VALUE_COLUMNS as $column => $expected ) {
			$test->assertSame(
				$expected,
				(string) ( $dest_array[ $column ] ?? '' ),
				"wp_posts column '{$column}' should be the WP default '{$expected}'"
			);
		}
	}

	/**
	 * Asserts that every wp_posts column is classified (parity rule,
	 * divergence registry, or deferred registry). Fails loudly when a column
	 * is unmodeled so adding columns or omitting them from the rules
	 * surfaces visibly instead of being silently skipped.
	 *
	 * @param TestCase $test Active test case.
	 */
	public static function assert_no_unmodeled_columns( TestCase $test ): void {
		$classified = array_merge(
			array_values( self::IDENTITY_COLUMNS ),
			array_values( self::CONTENT_COLUMNS ),
			array_values( self::STATUS_COLUMNS ),
			array_values( self::MISC_COLUMNS ),
			array_keys( self::DEFAULT_VALUE_COLUMNS ),
			array_keys( self::DIVERGENCE_REGISTRY ),
			array_keys( self::DEFERRED_REGISTRY )
		);

		$unmodeled = array_values(
			array_diff( self::WP_POSTS_COLUMNS, $classified )
		);

		$test->assertSame(
			array(),
			$unmodeled,
			'Every wp_posts column must be classified; unmodeled columns: '
			. implode( ', ', $unmodeled )
		);
	}

	/**
	 * Asserts that every meta key in the source body's `meta` field
	 * round-trips to the destination post unchanged.
	 *
	 * Compares with string coercion because update_post_meta() serializes
	 * scalars as strings — int 5 becomes "5" on the way back through
	 * get_post_meta(). Array values aren't seeded yet; when they appear, this
	 * helper will need a deserialization-aware comparison.
	 *
	 * @param array<string, mixed> $source_body Source REST response body.
	 * @param WP_Post              $dest_post   Imported destination post.
	 * @param TestCase             $test        Active test case.
	 */
	public static function assert_source_matched_meta(
		array $source_body,
		WP_Post $dest_post,
		TestCase $test
	): void {
		$source_meta = (array) ( $source_body['meta'] ?? array() );

		foreach ( $source_meta as $key => $value ) {
			$key        = (string) $key;
			$dest_value = get_post_meta( $dest_post->ID, $key, true );

			$test->assertSame(
				self::coerce_meta_value_for_comparison( $value ),
				self::coerce_meta_value_for_comparison( $dest_value ),
				"Meta key '{$key}' should round-trip from source to dest"
			);
		}
	}

	/**
	 * Asserts that every plugin-added meta key carries the expected value.
	 *
	 * META_SOURCE_POST_ID, META_SOURCE_LINK, META_IMPORTED_FROM, and the
	 * source-author meta values are deterministic and asserted strictly.
	 * META_IMPORT_DATE_GMT is checked for shape only (MySQL datetime format)
	 * because the timestamp depends on import wall time.
	 *
	 * @param array<string, mixed> $source_body Source REST response body.
	 * @param WP_Post              $dest_post   Imported destination post.
	 * @param TestCase             $test        Active test case.
	 */
	public static function assert_plugin_added_meta(
		array $source_body,
		WP_Post $dest_post,
		TestCase $test
	): void {
		$source_author = (array) ( $source_body['safe_publish_author'] ?? array() );
		$source_id     = (string) ( $source_body['id'] ?? '' );
		$source_link   = (string) ( $source_body['link'] ?? '' );
		$author_email  = (string) ( $source_author['email'] ?? '' );
		$author_login  = (string) ( $source_author['login'] ?? '' );

		$expected = array(
			Options::META_SOURCE_POST_ID      => $source_id,
			Options::META_SOURCE_LINK         => $source_link,
			Options::META_IMPORTED_FROM       => Options::META_IMPORTED_FROM_VALUE,
			Options::META_SOURCE_AUTHOR_EMAIL => $author_email,
			Options::META_SOURCE_AUTHOR_LOGIN => $author_login,
		);

		foreach ( $expected as $key => $expected_value ) {
			$actual = (string) get_post_meta( $dest_post->ID, $key, true );
			$test->assertSame(
				$expected_value,
				$actual,
				"Plugin-added meta '{$key}' should match the expected value"
			);
		}

		$import_date = (string) get_post_meta(
			$dest_post->ID,
			Options::META_IMPORT_DATE_GMT,
			true
		);
		$test->assertMatchesRegularExpression(
			'/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/',
			$import_date,
			'META_IMPORT_DATE_GMT should be a MySQL datetime string'
		);
	}

	/**
	 * Asserts that every meta key present on the destination post is
	 * classified: a key from the source body's `meta` field, a plugin-added
	 * key, an allowed WordPress default, or a deferred key reserved for a
	 * later phase. Fails loudly when an unmodeled key appears so the
	 * registries stay synced with what the import pipeline actually writes.
	 *
	 * @param array<string, mixed> $source_body Source REST response body.
	 * @param WP_Post              $dest_post   Imported destination post.
	 * @param TestCase             $test        Active test case.
	 */
	public static function assert_no_unmodeled_meta_keys(
		array $source_body,
		WP_Post $dest_post,
		TestCase $test
	): void {
		$source_meta_keys = array_map(
			'strval',
			array_keys( (array) ( $source_body['meta'] ?? array() ) )
		);

		$classified = array_values(
			array_unique(
				array_merge(
					$source_meta_keys,
					array_keys( self::PLUGIN_ADDED_META ),
					array_keys( self::WP_DEFAULT_META ),
					array_keys( self::DEFERRED_META )
				)
			)
		);

		$dest_meta_keys = array_keys( (array) get_post_meta( $dest_post->ID ) );
		$unmodeled      = array_values(
			array_diff( $dest_meta_keys, $classified )
		);

		$test->assertSame(
			array(),
			$unmodeled,
			sprintf(
				'Every dest meta key on post %d must be classified;'
				. ' unmodeled: %s',
				$dest_post->ID,
				implode( ', ', $unmodeled )
			)
		);
	}

	/**
	 * Asserts that every meta key listed in DEFERRED_META is absent on the
	 * destination post. Locks the current phase's behavior so that when a
	 * later phase starts emitting one of these keys (e.g. PR 2c attaching
	 * `_thumbnail_id`), the test fails and forces an explicit move out of
	 * DEFERRED_META into PLUGIN_ADDED_META.
	 *
	 * @param WP_Post  $dest_post Imported destination post.
	 * @param TestCase $test      Active test case.
	 */
	public static function assert_deferred_meta_absent(
		WP_Post $dest_post,
		TestCase $test
	): void {
		foreach ( self::DEFERRED_META as $key => $reason ) {
			$test->assertFalse(
				metadata_exists( 'post', $dest_post->ID, $key ),
				"Deferred meta '{$key}' should be absent in current phase"
				. " ({$reason}); move it to PLUGIN_ADDED_META when the"
				. ' phase that emits it ships.'
			);
		}
	}

	/**
	 * Asserts that every taxonomy assignment in the source body has a
	 * matching dest term and that the dest post is assigned to it.
	 *
	 * Source assignments come from `_embedded['wp:term']`, where each entry
	 * carries a taxonomy and a name. The importer resolves dest terms by
	 * slug (`sanitize_title( name )`) and creates the term if missing. This
	 * helper also reverse-asserts that dest terms land with parent=0 and
	 * description='' to lock in the importer's default-create behavior — a
	 * future change that propagates parent or description must update this
	 * assertion alongside the import code.
	 *
	 * @param array<string, mixed> $source_body Source REST response body.
	 * @param WP_Post              $dest_post   Imported destination post.
	 * @param TestCase             $test        Active test case.
	 */
	public static function assert_term_assignments(
		array $source_body,
		WP_Post $dest_post,
		TestCase $test
	): void {
		$source_assignments = self::source_term_assignments( $source_body );

		foreach ( $source_assignments as $taxonomy => $names ) {
			foreach ( $names as $name ) {
				$slug = sanitize_title( $name );
				$term = get_term_by( 'slug', $slug, $taxonomy );

				$test->assertNotFalse(
					$term,
					"Source term '{$name}' (slug '{$slug}') should exist"
					. " on dest in taxonomy '{$taxonomy}'"
				);

				$test->assertSame(
					$name,
					(string) $term->name,
					"Dest term '{$slug}' in '{$taxonomy}' should keep its"
					. ' source name'
				);
				$test->assertSame(
					0,
					(int) $term->parent,
					"Dest term '{$slug}' in '{$taxonomy}' should have"
					. ' parent=0 (importer default)'
				);
				$test->assertSame(
					'',
					(string) $term->description,
					"Dest term '{$slug}' in '{$taxonomy}' should have"
					. ' empty description (importer default)'
				);

				$test->assertTrue(
					has_term( $term->term_id, $taxonomy, $dest_post ),
					"Dest post should be assigned term '{$slug}' in"
					. " '{$taxonomy}'"
				);
			}
		}
	}

	/**
	 * Asserts that every dest term assignment in a checked taxonomy traces
	 * back to a source assignment. Fails loudly if the importer ever attaches
	 * a term the source didn't ask for.
	 *
	 * @param array<string, mixed> $source_body Source REST response body.
	 * @param WP_Post              $dest_post   Imported destination post.
	 * @param TestCase             $test        Active test case.
	 */
	public static function assert_no_unmodeled_term_assignments(
		array $source_body,
		WP_Post $dest_post,
		TestCase $test
	): void {
		$source_slugs_by_taxonomy = array();
		foreach (
			self::source_term_assignments( $source_body ) as $taxonomy => $names
		) {
			foreach ( $names as $name ) {
				$source_slugs_by_taxonomy[ $taxonomy ][ sanitize_title( $name ) ]
					= true;
			}
		}

		foreach ( self::TERM_TAXONOMIES_CHECKED as $taxonomy ) {
			$dest_terms = wp_get_object_terms( $dest_post->ID, $taxonomy );
			$test->assertNotInstanceOf(
				WP_Error::class,
				$dest_terms,
				"wp_get_object_terms('{$taxonomy}') returned WP_Error;"
				. ' check TERM_TAXONOMIES_CHECKED for taxonomies that'
				. ' are registered on the test site'
			);

			foreach ( (array) $dest_terms as $term ) {
				$test->assertArrayHasKey(
					$term->slug,
					$source_slugs_by_taxonomy[ $taxonomy ] ?? array(),
					"Dest post has term '{$term->slug}' in '{$taxonomy}'"
					. ' with no matching source assignment'
				);
			}
		}
	}

	/**
	 * Reads `_embedded['wp:term']` and returns a flat taxonomy => list of
	 * names map.
	 *
	 * @param array<string, mixed> $source_body Source REST response body.
	 * @return array<string, list<string>>
	 */
	private static function source_term_assignments( array $source_body ): array {
		$assignments = array();
		$embedded    = $source_body['_embedded']['wp:term'] ?? array();

		foreach ( (array) $embedded as $group ) {
			foreach ( (array) $group as $term ) {
				$taxonomy = (string) ( $term['taxonomy'] ?? '' );
				$name     = (string) ( $term['name'] ?? '' );
				if ( '' === $taxonomy || '' === $name ) {
					continue;
				}
				$assignments[ $taxonomy ][] = $name;
			}
		}

		return $assignments;
	}

	/**
	 * Coerces a meta value to a comparable representation. Scalars become
	 * strings because update_post_meta() stores them that way; arrays and
	 * objects pass through unchanged so deserialized values still compare
	 * structurally when they're seeded in a future phase.
	 *
	 * @param mixed $value Raw meta value.
	 * @return mixed
	 */
	private static function coerce_meta_value_for_comparison( mixed $value ): mixed {
		return is_scalar( $value ) ? (string) $value : $value;
	}

	/**
	 * Applies assertSame across a source-field => column mapping.
	 *
	 * Handles `[ 'raw' => string ]` REST wrappers transparently and falls
	 * back to the raw scalar when the field isn't wrapped.
	 *
	 * @param array<string, string> $mapping     Source field => wp_posts column.
	 * @param array<string, mixed>  $source_body Source REST response body.
	 * @param WP_Post               $dest_post   Imported destination post.
	 * @param TestCase              $test        Active test case.
	 */
	private static function assert_mapped_columns(
		array $mapping,
		array $source_body,
		WP_Post $dest_post,
		TestCase $test
	): void {
		$dest_array = $dest_post->to_array();

		foreach ( $mapping as $source_field => $column ) {
			$source_value = self::source_value( $source_body, $source_field );
			$dest_value   = $dest_array[ $column ] ?? null;

			$test->assertSame(
				$source_value,
				$dest_value,
				"wp_posts column '{$column}' should match source"
				. " field '{$source_field}'"
			);
		}
	}

	/**
	 * Reads a source REST body field, unwrapping `[ 'raw' => ... ]` wrappers.
	 *
	 * @param array<string, mixed> $source_body Source REST response body.
	 * @param string               $field       Top-level field name.
	 * @return mixed Raw field value.
	 */
	private static function source_value( array $source_body, string $field ): mixed {
		$value = $source_body[ $field ] ?? null;

		if ( is_array( $value ) && array_key_exists( 'raw', $value ) ) {
			return $value['raw'];
		}

		return $value;
	}
}
